def _array(table: str, column: str, nullable: bool = False) -> str:
    cond = f"jsonb_typeof({column}) = 'array'"
    if nullable:
        cond = f"{column} IS NULL OR {cond}"
    return f"CONSTRAINT ck_{table}_{column}_array CHECK ({cond})"


def _object(table: str, column: str, nullable: bool = False) -> str:
    cond = f"jsonb_typeof({column}) = 'object'"
    if nullable:
        cond = f"{column} IS NULL OR {cond}"
    return f"CONSTRAINT ck_{table}_{column}_object CHECK ({cond})"


